import hashlib

# ===== ค่าคงที่ =====
HASH_MAX = 2 ** 64  # ค่าสูงสุดของตำแหน่งบนแหวน (0 ถึงนี้)

# ===== ฟังก์ชันแฮชมาตรฐาน — ห้ามแก้เอง =====
def hash_to_64bit(text: str) -> int:
    """
    แปลงข้อความให้เป็นตำแหน่ง 64 บิตบนแหวน
    ค่าเดิมเสมอทุกครั้ง แม้ปิดเปิดโปรแกรมใหม่
    """
    result = hashlib.sha256(text.encode("utf-8")).hexdigest()
    return int(result[:16], 16)  # ตัดเอา 64 บิตแรก

# ===== สูตรคำนวณหมายเลขห้อง — ห้ามแก้เอง =====
def compute_room_number(c: int, s: int) -> int:
    """
    Cantor Pairing Function
    คืนเลขห้องที่ไม่ซ้ำสำหรับคู่ (c, s) ต่างกัน
    """
    a = c - 1
    b = s - 1
    return (a + b) * (a + b + 1) // 2 + b + 1